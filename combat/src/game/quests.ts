export type QuestEvent = 'fightWin' | 'fightPlay' | 'fightWinStronger' | 'mineHours' | 'buyItem' | 'repair' | 'heal' | 'sharpen' | 'gather' | 'sellResources';

export interface QuestTemplate {
  id: string;
  event: QuestEvent;
  /** Заголовок с подстановкой цели. */
  title: (target: number) => string;
  /** Варианты цели; выбирается случайно. */
  targets: number[];
  /** Награда в кредитах за единицу цели, опыт считается от неё. */
  kreditsPer: number;
}

export interface QuestState {
  id: string;
  templateId: string;
  event: QuestEvent;
  target: number;
  progress: number;
  claimed: boolean;
}

export interface QuestBoard {
  /** Локальная дата YYYY-MM-DD. На следующий день доска пересоздаётся. */
  day: string;
  quests: QuestState[];
}

/** Склонение по числу: один / два-четыре / пять и больше. */
function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
}

